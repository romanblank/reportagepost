-- Идемпотентность вебхука по PaymentId (S5-блокер, аудит 2026-07-26).
--
-- Повторная доставка вебхука уже защищена claim-ом по нашему OrderId, но сама
-- Т-Касса при ретраях присылает один и тот же PaymentId. Уникальность на нём —
-- второй рубеж: даже если платёж окажется привязан к другому OrderId, дважды
-- зачислить период не выйдет. Для денег «почти идемпотентно» не считается.
--
-- SAFE-TO-ROLLBACK: только уникальный индекс; NULL-значения он не ограничивает,
-- поэтому существующие записи без PaymentId не мешают.

CREATE UNIQUE INDEX "Payment_tinkoffPaymentId_key" ON "Payment"("tinkoffPaymentId");
