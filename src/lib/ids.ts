import { randomUUID } from 'node:crypto';

/**
 * Идентификатор, сгенерированный ДО записи.
 *
 * Обычно id ставит Prisma по умолчанию, но адрес темы содержит хвост от id, а
 * значит id нужен раньше вставки. Альтернатива — вставить, а потом обновить
 * slug — оставляет строку с пустым адресом в чужой видимости на время между
 * запросами.
 */
export function createId(): string {
  return randomUUID().replace(/-/g, '');
}
