/** Акт — уровень Active+. */
function act(a: AuthorContext): string {
  return `АКТ СДАЧИ-ПРИЁМКИ ОКАЗАННЫХ УСЛУГ
к договору № ______ от «___» __________ 20___ г.

г. ${a.cityName}                                    «___» ____________ 20___ г.

${field(a.legalName, 'наименование')}, ИНН ${field(a.inn, 'ИНН')},
именуемый «Исполнитель», и ______________________________________,
именуемое «Заказчик», составили настоящий Акт о нижеследующем.

1. Исполнитель оказал, а Заказчик принял услуги по репортажной фотосъёмке
   события _________________________________, состоявшегося «___» _______ 20___ г.

2. Объём оказанных услуг соответствует условиям договора и брифа.
   Передано обработанных фотографий: ______ шт.
   Способ передачи: _______________________________________

3. Стоимость оказанных услуг составляет ______________ рублей.
   НДС не облагается (уточните формулировку под свой налоговый режим).

4. Услуги оказаны в полном объёме и в согласованные сроки.
   Заказчик претензий по объёму, качеству и срокам не имеет.

Исполнитель:                          Заказчик:
_______________ / ${a.lastName} ${a.firstName[0]}. /      _______________ / ____________ /
${footer()}`;
}

const BUILDERS: Record<SalesDocKind, (a: AuthorContext) => string> = {
  brief,
  checklist,
  proposal,
  contract,
  invoice,
  act,
};

/** Минимальный уровень подписки для каждого документа. */
export const DOC_MIN_TIER: Record<SalesDocKind, 'FREE' | 'PRIME' | 'ELITE'> = {
  // Бриф и чек-лист бесплатны: они не про деньги автора, а про качество
  // съёмки. Плохо снятое событие вредит всей платформе, поэтому запирать их
  // за подписку — вредить себе.
  brief: 'FREE',
  checklist: 'FREE',
  proposal: 'PRIME',
  contract: 'PRIME',
  invoice: 'ELITE',
  act: 'ELITE',
};

export function buildSalesDoc(kind: SalesDocKind, author: AuthorContext): string {
  return BUILDERS[kind](author);
}
