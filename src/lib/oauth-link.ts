/**
 * Гард линковки OAuth-входа к СУЩЕСТВУЮЩЕМУ аккаунту по email.
 *
 * Связывать можно только с аккаунтом, который заведомо принадлежит этому же
 * человеку: подтверждённым адресом или созданным через вход без пароля.
 * Иначе получается захват: злоумышленник регистрирует аккаунт на ЧУЖУЮ почту
 * (подтверждение при регистрации не требуется), задаёт свой пароль — и когда
 * настоящий владелец адреса входит через Яндекс, он попадает в аккаунт,
 * пароль от которого знает чужой человек.
 *
 * До аудита 2026-09-10 правило жило ДВУМЯ инлайн-копиями (callback и
 * complete) — единственный барьер от захвата аккаунта, у которого будущая
 * правка с высокой вероятностью попала бы в один файл из двух. Теперь копия
 * одна, и тест стережёт один источник истины.
 */
export function safeToLink(user: { emailVerifiedAt: Date | null; passwordHash: string | null }): boolean {
  return Boolean(user.emailVerifiedAt) || !user.passwordHash;
}
