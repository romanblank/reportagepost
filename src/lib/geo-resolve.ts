import { db } from '@/lib/db';
import { RU_COUNTRY } from '@/lib/geo-data';

/**
 * Резолвер города по слагу (аудит 2026-08-01, P2).
 *
 * Слаг города уникален ТОЛЬКО внутри страны — так и объявлено в схеме
 * (@@unique([countryId, slug])). Но шесть серверных путей (анкета фотографа,
 * заявка заказчика, выездной график, админ-онбординг) резолвили его через
 * findFirst({ where: { slug } }), полагаясь на глобальную уникальность, которой
 * нет. Публичные страницы каталога делали это правильно — код расходился сам с
 * собой.
 *
 * Инвариант проекта — задел на мир с первого дня. В момент активации второй
 * страны первый же совпадающий слаг (moscow есть в США, victoria — в Канаде и
 * Австралии, таких десятки) отправил бы анкету, заявку или выездной график в
 * город другой страны. Молча: findFirst просто вернул бы произвольную строку.
 * Проявилось бы как «мой профиль исчез из каталога» — и диагностировалось бы
 * крайне тяжело.
 *
 * Страна пока всегда одна (РФ-старт), но передаётся явно, чтобы включение
 * второй не потребовало заново искать все места.
 */
export async function resolveCity(citySlug: string, countrySlug: string = RU_COUNTRY.slug) {
  const country = await db.country.findUnique({ where: { slug: countrySlug }, select: { id: true } });
  if (!country) return null;
  return db.city.findUnique({
    where: { countryId_slug: { countryId: country.id, slug: citySlug } },
  });
}
