import { revalidateTag } from 'next/cache';

/**
 * Сброс кэша, безопасный вне запроса.
 *
 * `revalidateTag` работает только внутри обработки запроса Next. Те же
 * доменные функции вызываются из фоновых задач, скриптов обслуживания и
 * тестов — там сбрасывать нечего, а исключение уронило бы саму операцию:
 * модерация кадра не должна падать из-за кэша.
 */
export function dropCache(...tags: string[]): void {
  for (const tag of tags) {
    try {
      revalidateTag(tag, 'max');
    } catch {
      // Вне запроса кэша нет — это нормальный режим для заданий и скриптов
    }
  }
}
