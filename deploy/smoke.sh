#!/usr/bin/env bash
# Пост-деплой smoke на проде: проверяем не «контейнер жив», а «сайт работает».
#
# /health отвечает 200 даже когда каталог падает на рендере: он трогает только
# базу. Здесь проверяются реальные страницы и КОДАМИ ОТВЕТА, а не разметкой —
# при SSR-стриминге ранний HTML (шапка) уходит клиенту до ошибки в компоненте
# ниже, и grep по маркеру находит его на битой странице (наступали, ложная
# зелень маскировала сломанный профиль пять деплоев подряд).
#
# Возврат 1 означает «прод неисправен» — вызывающий деплой откатывается.
set -uo pipefail
B="${SMOKE_BASE:-http://127.0.0.1:$(/usr/local/bin/rp-port.sh 2>/dev/null || echo 3000)}"
FAIL=0

check() { # $1 — путь, $2 — ожидаемый код, $3 — что это
  local code
  code=$(curl -s -o /dev/null -m 20 -w '%{http_code}' "$B$1")
  if [ "$code" != "$2" ]; then
    echo "SMOKE ✗ $3 ($1): получили $code, ждали $2"
    FAIL=1
  else
    echo "SMOKE ✓ $3 ($1): $code"
  fi
}

# Живые страницы: сюда приходит заказчик
check "/" 200 "главная"
check "/ru/russia/moscow" 200 "каталог города"
check "/ru/russia/moscow/sports" 200 "каталог жанра"
check "/ru/match" 200 "подбор"
check "/ru/pro" 200 "подписка"
check "/ru/login" 200 "вход"
check "/ru/register" 200 "регистрация"

# Честный 404 — регрессия soft-404 возвращала сюда 200 и кормила поисковик
# мусорными адресами (закрыто proxy.ts, стережём на проде тоже)
check "/ru/russia/nowhere" 404 "несуществующий город"
check "/ru/photographer/no-such-author-xyz" 404 "несуществующий автор"

# Раздатчик медиа: несуществующий ключ — это 404, а не 500
check "/files/photos/no-such-key/web.jpg" 404 "неизвестный файл"

if [ "$FAIL" -ne 0 ]; then
  echo "SMOKE: прод неисправен"
  exit 1
fi
echo "SMOKE: всё в порядке"
